import pandas as pd

customers = {
    "name": ["Nia", "Omar", "Priya", "Leo"],
    "channel": ["Organic", "Paid Search", "Referral", "Organic"],
    "purchases": [2, 0, 1, 0],
    "revenue": [200, 0, 120, 0]
}

df = pd.DataFrame(customers)

df["has_purchased"] = df["purchases"] > 0

print(df)

# Total purchases by acquisition channel
channel_purchases = df.groupby("channel")["purchases"].sum()

print(channel_purchases)


# Number of purchasing customers by channel
channel_customers = df.groupby("channel")["has_purchased"].sum()

print(channel_customers)


# What is the total revenue generated by each acquisition channel?
channel_revenue = df.groupby("channel")["revenue"].sum()
print(channel_revenue)


# Step 1: Aggregate customer metrics by channel
channel_summary = df.groupby("channel").agg(
    purchasing_customers=("has_purchased", "sum"),
    total_purchases=("purchases", "sum"),
    total_revenue=("revenue", "sum"),
    total_customers=("name", "size")
)

# Step 2: Calculate purchaser rate using the summary columns
channel_summary["purchaser_rate_pct"] = (
    channel_summary["purchasing_customers"]
    / channel_summary["total_customers"]
) * 100

# Step 3: Display the completed report
print(channel_summary)


# How much revenue do we generate per registered customer in each acquisition channel?
channel_summary["revenue_per_customer"] = (channel_summary["total_revenue"] / channel_summary["total_customers"])
print(channel_summary)



ranked_channels = channel_summary.sort_values(
    "revenue_per_customer",
    ascending=False
    )

print(ranked_channels)